static mut CURSOR_X: usize = 0;
static mut CURSOR_Y: usize = 0;

pub struct Screen;

impl Screen {
    pub fn init() {
        // Open Graphics Output Protocol
        let gop_handle = uefi::boot::get_handle_for_protocol::<GraphicsOutput>().expect(concatcp!(
            ERROR_FLAG,
            "Failed to get graphics output protocol handle."
        ));

        let mut gop = uefi::boot::open_protocol_exclusive::<GraphicsOutput>(gop_handle).expect(
            concatcp!(ERROR_FLAG, "Failed to open graphics output protocol."),
        );

        // Get GOP information
        let mode_info = gop.current_mode_info();
        let (screen_width, screen_height) = mode_info.resolution();
        let stride = mode_info.stride();
        let pixel_format = mode_info.pixel_format();

        // Get frame buffer address
        let mut fb = gop.frame_buffer();
        let fb_ptr = fb.as_mut_ptr();

        unsafe {
            SCREEN_WIDTH = screen_width;
            SCREEN_HEIGHT = screen_height;
            STRIDE = stride;
            PIXEL_FORMAT = pixel_format;
            FB_PTR = fb_ptr;
        }
    }

    pub fn clear() {
        unsafe {
            let total_bytes = STRIDE * SCREEN_HEIGHT * 4;

            // Write 0 to all bytes in the frame buffer
            core::ptr::write_bytes(FB_PTR, 0, total_bytes);

            CURSOR_X = 0;
            CURSOR_Y = 0;
        }
    }

    pub fn draw_pixel(x: usize, y: usize, color: (u8, u8, u8)) {
        unsafe {
            // Pixel coordinates not valid
            if x >= SCREEN_WIDTH || y >= SCREEN_HEIGHT {
                return;
            }

            let pixel_offset = y * STRIDE + x;

            let pixel_ptr = FB_PTR.add(pixel_offset * 4); // Calculate pixel bytes position in frame buffer

            // Draw pixel color based on pixel format
            match PIXEL_FORMAT {
                PixelFormat::Rgb => {
                    *pixel_ptr.add(0) = color.0;
                    *pixel_ptr.add(1) = color.1;
                    *pixel_ptr.add(2) = color.2;
                    *pixel_ptr.add(3) = 0;
                }
                PixelFormat::Bgr => {
                    *pixel_ptr.add(0) = color.2;
                    *pixel_ptr.add(1) = color.1;
                    *pixel_ptr.add(2) = color.0;
                    *pixel_ptr.add(3) = 0;
                }
                _ => {}
            }
        }
    }

    pub fn draw_char(c: char, x: usize, y: usize) {
        // Get char in font
        let char_index = c as usize - 0x20;
        let char_font = FONT[char_index];

        // Draw each line of pixels
        for col in 0..8 {
            let mut bits = char_font[col];

            for row in 0..8 {
                let bit = (bits & 0x80) >> 7;

                for pixel_col in 0..FONT_SCALE {
                    for pixel_row in 0..FONT_SCALE {
                        Self::draw_pixel(
                            x + row * FONT_SCALE + pixel_col,
                            y + col * FONT_SCALE + pixel_row,
                            (255 * bit, 255 * bit, 255 * bit),
                        );
                    }
                }

                bits <<= 1;
            }
        }
    }

    pub fn draw_string(s: &str, x: usize, y: usize) {
        let mut cursor_x = x;
        let mut cursor_y = y;

        for c in s.chars() {
            if c == '\n' {
                cursor_y += 8 * FONT_SCALE;
                continue;
            }

            if c == '\r' {
                cursor_x = x;
                continue;
            }

            // Prevent crashes from overflow or underflow
            if (c as usize) < 0x20 || (c as usize) >= 0x20 + FONT.len() {
                continue;
            }

            Self::draw_char(c, cursor_x, cursor_y);
            cursor_x += 8 * FONT_SCALE;
        }
    }

    fn draw_string_cursor(s: &str) {
        unsafe {
            for c in s.chars() {
                if c == '\n' {
                    CURSOR_Y += 8 * FONT_SCALE;
                    continue;
                }

                if c == '\r' {
                    CURSOR_X = 0;
                    continue;
                }

                if c == '\x08' {
                    CURSOR_X -= 8 * FONT_SCALE;
                }

                // Prevent crashes from overflow or underflow
                if (c as usize) < 0x20 || (c as usize) >= 0x20 + FONT.len() {
                    continue;
                }

                Self::draw_char(c, CURSOR_X, CURSOR_Y);
                CURSOR_X += 8 * FONT_SCALE;
            }
        }
    }
}

impl core::fmt::Write for Screen {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        Self::draw_string_cursor(s);
        Ok(())
    }
}

